# mkfont.py -- bake printable ASCII of a TTF into src/app/font_data.h:
# an 8-bit coverage atlas plus per-glyph metrics, so the app needs no font
# library at run time.  usage: python3 tools/mkfont.py FONT.ttf PX > src/app/font_data.h
import sys
from PIL import Image, ImageDraw, ImageFont
path, px = sys.argv[1], int(sys.argv[2])
font = ImageFont.truetype(path, px)
asc, desc = font.getmetrics()
H = asc + desc
glyphs = []
x = 0
for c in range(32, 127):
    ch = chr(c)
    adv = font.getlength(ch)
    l, t, r, b = font.getbbox(ch)
    w = max(1, r - min(l, 0))
    glyphs.append((c, x, w, min(l, 0), adv))
    x += w + 1
W = x
img = Image.new("L", (W, H), 0)
d = ImageDraw.Draw(img)
for c, gx, w, l, adv in glyphs:
    d.text((gx - l, 0), chr(c), font=font, fill=255)
px_ = img.load()
print("/* Generated by tools/mkfont.py from %s at %dpx; do not edit." % (path.split('/')[-1], px))
print("   The glyphs are DejaVu Sans: see third_party/dejavu/LICENSE. */")
print("#define FONT_ATLAS_W %d\n#define FONT_ATLAS_H %d\n#define FONT_ASCENT %d" % (W, H, asc))
print("static const struct { short x, w, ox; float adv; } font_glyphs[95] = {")
print(",\n".join("  {%d,%d,%d,%.3ff}" % (gx, w, l, adv) for c, gx, w, l, adv in glyphs))
print("};")
print("static const unsigned char font_atlas[%d] = {" % (W * H))
row = []
for yy in range(H):
    for xx in range(W):
        row.append(str(px_[xx, yy]))
for i in range(0, len(row), 32):
    print("  " + ",".join(row[i:i+32]) + ",")
print("};")
